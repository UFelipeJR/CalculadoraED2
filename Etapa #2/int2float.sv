                32'b01??????????????????????????????: msb_index = 30;
                32'b001?????????????????????????????: msb_index = 29;
                32'b0001????????????????????????????: msb_index = 28;
                32'b00001???????????????????????????: msb_index = 27;
                32'b000001??????????????????????????: msb_index = 26;
                32'b0000001?????????????????????????: msb_index = 25;
                32'b00000001????????????????????????: msb_index = 24;
                32'b000000001???????????????????????: msb_index = 23;
                32'b0000000001??????????????????????: msb_index = 22;
                32'b00000000001?????????????????????: msb_index = 21;
                32'b000000000001????????????????????: msb_index = 20;
                32'b0000000000001???????????????????: msb_index = 19;
                32'b00000000000001??????????????????: msb_index = 18;
                32'b000000000000001?????????????????: msb_index = 17;
                32'b0000000000000001????????????????: msb_index = 16;
                32'b00000000000000001???????????????: msb_index = 15;
                32'b000000000000000001??????????????: msb_index = 14;
                32'b0000000000000000001?????????????: msb_index = 13;
                32'b00000000000000000001????????????: msb_index = 12;
                32'b000000000000000000001???????????: msb_index = 11;
