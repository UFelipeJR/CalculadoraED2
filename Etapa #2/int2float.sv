                32'b00000000000000000000001?????????: msb_index = 9;
                32'b000000000000000000000001????????: msb_index = 8;
                32'b0000000000000000000000001???????: msb_index = 7;
                32'b00000000000000000000000001??????: msb_index = 6;
                32'b000000000000000000000000001?????: msb_index = 5;
                32'b0000000000000000000000000001????: msb_index = 4;
                32'b00000000000000000000000000001???: msb_index = 3;
                32'b000000000000000000000000000001??: msb_index = 2;
                32'b0000000000000000000000000000001?: msb_index = 1;
                32'b00000000000000000000000000000001: msb_index = 0;
                default: msb_index = 0;
            endcase
            expo = msb_index + 8'd127;
            if (msb_index >= 23)
                normalized = abs_value >> (msb_index - 23);
            else
