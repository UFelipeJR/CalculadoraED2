module int2float(
    input logic [31:0] A,
    output logic [31:0] C
);
    logic sign;
    logic [31:0] abs_value;
    logic [7:0] expo;
    logic [22:0] mantissa;
    logic [5:0] msb_index;  
    logic [31:0] normalized;
    always_comb begin
        sign = A[31];
        abs_value = sign ? (~A + 1'b1) : A;
        expo = 0;
        mantissa = 0;
        msb_index = 0;
        normalized = 0;
        if (A == 0) begin
            C = 32'b0;
        end else begin
            casez (abs_value)
