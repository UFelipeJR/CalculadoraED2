            mantissa = normalized[22:0];
            C = {sign, expo, mantissa};
        end
    end
endmodule


module tb_int2float;
  // Entradas y salidas
  logic [31:0] A;
  logic [31:0] C;

  // Instancia del módulo
  int2float uut (
    .A(A),
    .C(C)
  );

  // Tarea para mostrar resultado con valor esperado
  task test_case(input logic [31:0] val, input string desc);
    A = val;
    #10;
    $display("%-30s | A (int) = %0d | C (hex) = %h", desc, $signed(val), C);
  endtask

  initial begin
    $display("%-30s | %-20s | %-12s", "Descripcion", "A (int)", "C (hex)");
    $display("%s", {"─"*70});

    test_case(32'd0,          "Cero");
    test_case(32'd1,          "Uno");
    test_case(32'd2,          "Dos");
    test_case(32'd3,          "Tres");
    test_case(32'd10,         "Diez");
    test_case(32'd100,        "Cien");
    test_case(32'd1073741824, "2^30");
    test_case(32'hFFFFFFFF,   "Menos uno (-1)");
    test_case(32'h80000001,   "Entero negativo grande");
    test_case(32'h7FFFFFFF,   "INT_MAX (2147483647)");
    test_case(32'h80000000,   "INT_MIN (-2147483648)");

    $finish;
  end

  // Monitor general
  initial begin
    $monitor("A = %h | C = %h", A, C);
  end

endmodule